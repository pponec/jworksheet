package net.ponec.jworksheet.core.ujo;

import java.awt.Dimension;
import java.awt.Point;
import java.awt.Rectangle;
import java.lang.reflect.Field;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;
import org.ujorm.annotation.Domain;
import org.ujorm.core.DomainHandler;
import org.ujorm.core.DomainHandlerProvider;
import org.ujorm.core.Key;
import org.ujorm.tools.common.Primitive;

/**
 * Operations above the {@link Key} instances generated by the Ujorm annotation processor.
 * <p>The class adds the features the application needs but the Ujorm 3 does not provide:
 * a default value, a type of the list item and a name shared by the XML documents, the configuration file and the localization
 * bundles.
 * <p>The keys are singletons, so they can be compared by the {@code ==} operator.
 *
 * @author Pavel Ponec
 */
public final class Keys {

    /** A cache of the prototypes to resolve the default values. */
    private static final Map<Class<?>, Object> PROTOTYPES = new ConcurrentHashMap<>();

    /** A cache of the fields of the keys. */
    private static final Map<Key<?, ?>, Field> FIELDS = new ConcurrentHashMap<>();

    /** The domain class of a type: the type itself or its nearest superclass annotated by the {@code @Domain}. */
    private static final ClassValue<Class<?>> DOMAIN_CLASSES = new ClassValue<>() {
        @Override
        protected Class<?> computeValue(final Class<?> type) {
            for (Class<?> result = type; result != null; result = result.getSuperclass()) {
                if (result.isAnnotationPresent(Domain.class)) {
                    return result;
                }
            }
            throw new IllegalStateException("No class annotated by the @Domain: " + type.getName());
        }
    };

    private Keys() {
    }

    // ------------------------ THE METAMODEL ------------------------

    /** Is the type a domain object with its own keys? */
    public static boolean isDomain(final Class<?> type) {
        return DomainObject.class.isAssignableFrom(type);
    }

    /** Returns the domain class of the type: the type itself or its nearest superclass annotated by the {@code @Domain}. */
    static Class<?> domainClassOf(final Class<?> type) {
        return DOMAIN_CLASSES.get(type);
    }

    /** Returns all the keys of a domain class in the order of the field declaration. */
    public static <D extends DomainObject> List<Key<D, ?>> keysOf(final Class<D> domainClass) {
        return Keys.<D>handlerOf(domainClass).getKeyList();
    }

    /** Returns the handler of the {@code @Domain} class of the type. */
    @SuppressWarnings("unchecked")
    private static <D> DomainHandler<D> handlerOf(final Class<?> type) {
        return (DomainHandler<D>) DomainHandlerProvider.getHandler(domainClassOf(type));
    }

    /** Returns all the keys of a domain object whose type is not known at the compile time.
     * The keys are typed to the {@link Object}, so they can read and write a value
     * of any domain object without a cast. */
    @SuppressWarnings({"unchecked", "rawtypes"})
    public static List<Key<Object, Object>> keysOf(final DomainObject domain) {
        return (List) keysOf(domain.getClass());
    }

    /** Finds a key of the domain object by its exact name, see the {@link #nameOf(Key)}.
     * The handler finds the column case insensitive, so the exact name is checked here. */
    public static Optional<Key<Object, Object>> findKey(final DomainObject domain, final String name) {
        return Optional.ofNullable(handlerOf(domain.getClass()).<Object>getKeyByColumn(name, false, null))
                .filter(key -> nameOf(key).equals(name));
    }

    /** Returns a name of the key used by the XML documents, the configuration file and
     * the localization bundles. It is the {@code @UColumn} label of the field rather than
     * the Java field name. */
    public static String nameOf(final Key<?, ?> key) {
        return key.info().columnLabel();
    }

    /** Returns a type of the key value. A primitive type is provided as its wrapper,
     * because the Swing components can not handle a primitive class. */
    public static Class<?> typeOf(final Key<?, ?> key) {
        return Primitive.wrapPrimitive(key.type());
    }

    /** Is the key a collection of the domain objects? */
    public static boolean isList(final Key<?, ?> key) {
        return List.class.isAssignableFrom(key.type());
    }

    /** Returns a type of the list item. */
    public static Class<?> itemTypeOf(final Key<?, ?> key) {
        final Type type = fieldOf(key).getGenericType();
        if (type instanceof final ParameterizedType parametrized) {
            final Type[] arguments = parametrized.getActualTypeArguments();
            if (arguments.length == 1 && arguments[0] instanceof final Class<?> result) {
                return result;
            }
        }
        throw new IllegalStateException("The key is no generic list: " + fullNameOf(key));
    }

    /** Returns a field of the domain class which declares the key. */
    public static Field fieldOf(final Key<?, ?> key) {
        return FIELDS.computeIfAbsent(key, k -> {
            try {
                return k.domainClass().getDeclaredField(k.name());
            } catch (NoSuchFieldException e) {
                throw new IllegalStateException("No field of the key: " + fullNameOf(k), e);
            }
        });
    }

    /** A name of the key including its domain class, for the error messages. */
    public static String fullNameOf(final Key<?, ?> key) {
        return key.domainClass().getSimpleName() + '.' + key.name();
    }

    // ------------------------ THE VALUES ------------------------

    /** Copies a value of the key from one domain object to another one.
     * <p>A {@code null} assigned to a primitive field is replaced by its zero value
     * by the generated key itself. */
    public static <D, V> void copy(final Key<D, V> key, final D from, final D to) {
        key.setValue(to, key.getValue(from));
    }

    /** Returns a default value of the key.
     * <p>The Ujorm 3 does not know the default values, so the value is read from a prototype
     * instance of the domain class - the field initializers are the single source of the truth.
     * The prototype is created lazily and cached, so a dynamic default (a system locale
     * or a system login) is evaluated exactly once.
     * <p>A mutable value (a {@code Rectangle}, a {@code Dimension}, a {@code Date} or a {@code List})
     * is provided as a copy, so a caller can assign it to a domain object and modify it safely
     * - the default value of the application never changes. */
    @SuppressWarnings("unchecked")
    public static <D, V> V defaultOf(final Key<D, V> key) {
        return (V) copyOfMutable(sharedDefaultOf(key));
    }

    /** Returns the default value from the shared prototype without any copy, for reading only. */
    private static <D, V> V sharedDefaultOf(final Key<D, V> key) {
        return key.getValue(prototypeOf(key.domainClass()));
    }

    /** Returns a copy of a known mutable value, otherwise the original (immutable) value. */
    private static Object copyOfMutable(final Object value) {
        if (value instanceof final Rectangle r) {
            return new Rectangle(r);
        }
        if (value instanceof final Dimension d) {
            return new Dimension(d);
        }
        if (value instanceof final Point p) {
            return new Point(p);
        }
        if (value instanceof final Date d) {
            return d.clone();
        }
        if (value instanceof final List<?> list) {
            return new ArrayList<>(list);
        }
        return value;
    }

    /** Has the domain object the default value of the key? */
    public static <D, V> boolean isDefault(final Key<D, V> key, final D domain) {
        return isDefaultValue(key, key.getValue(domain));
    }

    /** Is the value equal to the default value of the key? */
    public static boolean isDefaultValue(final Key<?, ?> key, final Object value) {
        return Objects.equals(value, sharedDefaultOf(key));
    }

    /** Returns a shared prototype of the domain class to read the default values from. */
    @SuppressWarnings("unchecked")
    private static <D> D prototypeOf(final Class<D> domainClass) {
        return (D) PROTOTYPES.computeIfAbsent(domainClass, Keys::newInstance);
    }

    /** Creates a new instance of the domain class. */
    public static <D> D newInstance(final Class<D> domainClass) {
        try {
            return domainClass.getDeclaredConstructor().newInstance();
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("A domain class requires a public constructor"
                    + " without arguments: " + domainClass.getName(), e);
        }
    }
}
