package net.ponec.jworksheet.core.ujo;

import java.lang.reflect.Field;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import org.ujorm.core.DomainHandlerProvider;
import org.ujorm.core.Key;

/**
 * Operations above the {@link Key} instances generated by the Ujorm annotation processor.
 * <p>The class adds the features the application needs but the Ujorm 3 does not provide:
 * a default value, a type of the list item, a null normalization of the primitive fields
 * and a name shared by the XML documents, the configuration file and the localization
 * bundles.
 * <p>The keys are singletons, so they can be compared by the {@code ==} operator.
 *
 * @author Pavel Ponec
 */
public final class Keys {

    /** A cache of the prototypes to resolve the default values. */
    private static final Map<Class<?>, Object> PROTOTYPES = new HashMap<>();

    /** A cache of the fields of the keys. */
    private static final Map<Key<?, ?>, Field> FIELDS = new HashMap<>();

    private Keys() {
    }

    // ------------------------ THE METAMODEL ------------------------

    /** Returns all the keys of a domain class in the order of the field declaration. */
    public static <D> List<Key<D, ?>> keysOf(final Class<D> domainClass) {
        return DomainHandlerProvider.getHandler(domainClass).getKeyList();
    }

    /** Returns a name of the key used by the XML documents, the configuration file and
     * the localization bundles. It is the {@code @Column} label of the field rather than
     * the Java field name. */
    public static String nameOf(final Key<?, ?> key) {
        return key.info().columnLabel();
    }

    /** Returns a type of the key value. A primitive type is provided as its wrapper,
     * because the Swing components can not handle a primitive class. */
    public static Class<?> typeOf(final Key<?, ?> key) {
        return box(key.type());
    }

    /** Is the key a collection of the domain objects? */
    public static boolean isList(final Key<?, ?> key) {
        return List.class.isAssignableFrom(key.type());
    }

    /** Returns a type of the list item. */
    public static Class<?> itemTypeOf(final Key<?, ?> key) {
        final Type type = fieldOf(key).getGenericType();
        if (type instanceof final ParameterizedType parametrized) {
            final Type[] arguments = parametrized.getActualTypeArguments();
            if (arguments.length == 1 && arguments[0] instanceof final Class<?> result) {
                return result;
            }
        }
        throw new IllegalStateException("The key is no generic list: " + fullNameOf(key));
    }

    /** Returns a field of the domain class which declares the key. */
    public static Field fieldOf(final Key<?, ?> key) {
        synchronized (FIELDS) {
            Field result = FIELDS.get(key);
            if (result == null) {
                try {
                    result = key.domainClass().getDeclaredField(key.name());
                } catch (NoSuchFieldException e) {
                    throw new IllegalStateException("No field of the key: " + fullNameOf(key), e);
                }
                FIELDS.put(key, result);
            }
            return result;
        }
    }

    /** A name of the key including its domain class, for the error messages. */
    public static String fullNameOf(final Key<?, ?> key) {
        return key.domainClass().getSimpleName() + '.' + key.name();
    }

    // ------------------------ THE VALUES ------------------------

    /** Assigns a value to the domain object.
     * A {@code null} is normalized to a zero value for the keys backed by a primitive field. */
    @SuppressWarnings("unchecked")
    public static <D, V> void write(final Key<D, V> key, final D domain, final V value) {
        key.setValue(domain, value == null && key.type().isPrimitive()
                ? (V) zeroOf(key.type())
                : value);
    }

    /** Copies a value of the key from one domain object to another one. */
    public static <D, V> void copy(final Key<D, V> key, final D from, final D to) {
        write(key, to, key.getValue(from));
    }

    /** Returns a default value of the key.
     * <p>The Ujorm 3 does not know the default values, so the value is read from a prototype
     * instance of the domain class - the field initializers are the single source of the truth.
     * The prototype is created lazily and cached, so a dynamic default (a system locale
     * or a system login) is evaluated exactly once. */
    public static <D, V> V defaultOf(final Key<D, V> key) {
        return key.getValue(prototypeOf(key.domainClass()));
    }

    /** Has the domain object the default value of the key? */
    public static <D, V> boolean isDefault(final Key<D, V> key, final D domain) {
        return java.util.Objects.equals(key.getValue(domain), defaultOf(key));
    }

    /** Returns a shared prototype of the domain class to read the default values from. */
    @SuppressWarnings("unchecked")
    private static <D> D prototypeOf(final Class<D> domainClass) {
        synchronized (PROTOTYPES) {
            Object result = PROTOTYPES.get(domainClass);
            if (result == null) {
                result = newInstance(domainClass);
                PROTOTYPES.put(domainClass, result);
            }
            return (D) result;
        }
    }

    /** Creates a new instance of the domain class. */
    public static <D> D newInstance(final Class<D> domainClass) {
        try {
            return domainClass.getDeclaredConstructor().newInstance();
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("A domain class requires a public constructor"
                    + " without arguments: " + domainClass.getName(), e);
        }
    }

    // ------------------------ TOOLS ------------------------

    /** Returns a wrapper of the primitive type, or the original class. */
    public static Class<?> box(final Class<?> type) {
        if (!type.isPrimitive()) {
            return type;
        }
        if (type == boolean.class) { return Boolean.class; }
        if (type == byte.class) { return Byte.class; }
        if (type == char.class) { return Character.class; }
        if (type == short.class) { return Short.class; }
        if (type == int.class) { return Integer.class; }
        if (type == long.class) { return Long.class; }
        if (type == float.class) { return Float.class; }
        if (type == double.class) { return Double.class; }
        throw new IllegalArgumentException("Unsupported type: " + type);
    }

    /** Returns a zero value of the primitive type. */
    private static Object zeroOf(final Class<?> type) {
        if (type == boolean.class) { return Boolean.FALSE; }
        if (type == byte.class) { return (byte) 0; }
        if (type == char.class) { return (char) 0; }
        if (type == short.class) { return (short) 0; }
        if (type == int.class) { return 0; }
        if (type == long.class) { return 0L; }
        if (type == float.class) { return 0f; }
        if (type == double.class) { return 0d; }
        throw new IllegalArgumentException("Unsupported type: " + type);
    }
}
